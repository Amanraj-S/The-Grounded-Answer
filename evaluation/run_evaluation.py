def check_result(
    case,
    result,
):
    """
    Only evaluates the result returned by the
    production engine.

    No policy logic is implemented here.
    """

    if result["status"] != case["expected_status"]:
        return False

    answer = result.get(
        "answer",
        "",
    )

    citations = result.get(
        "citations",
        [],
    )

    expected_text = case.get(
        "expected_text"
    )

    if expected_text:

        if expected_text.lower() not in answer.lower():
            return False

    expected_citation = case.get(
        "expected_citation"
    )

    if expected_citation:

        if expected_citation not in citations:
            return False

    expected_citations = case.get(
        "expected_citations"
    )

    if expected_citations:

        for citation in expected_citations:

            if citation not in citations:
                return False

    return True


def write_results(results):
    """
    Generate evaluation/results.md.
    """

    total = len(results)

    passed = sum(
        1
        for result in results
        if result["passed"]
    )

    failed = total - passed

    lines = [
        "# Grounded Answer — Evaluation Results",
        "",
        "Automatically generated by "
        "`evaluation/run_evaluation.py`.",
        "",
        f"**Total:** {total}",
        f"**Passed:** {passed}",
        f"**Failed:** {failed}",
        "",
        "## Summary",
        "",
        "| # | Test Case | Expected | Actual | Result |",
        "|---|---|---|---|---|",
    ]

    for item in results:

        status = (
            "PASS"
            if item["passed"]
            else "FAIL"
        )

        lines.append(
            f"| {item['id']} | "
            f"{item['name']} | "
            f"{item['expected']} | "
            f"{item['actual']} | "
            f"**{status}** |"
        )

    lines.extend(
        [
            "",
            "## Detailed Results",
            "",
        ]
    )

    for item in results:

        status = (
            "PASS"
            if item["passed"]
            else "FAIL"
        )

        lines.extend(
            [
                f"### {item['id']}. "
                f"{item['name']}",
                "",
                f"**Question:** "
                f"{item['question']}",
                "",
                f"**Expected:** "
                f"`{item['expected']}`",
                "",
                f"**Actual:** "
                f"`{item['actual']}`",
                "",
                f"**Result:** **{status}**",
                "",
                f"**Topic:** "
                f"`{item['topic']}`",
                "",
                f"**Change date:** "
                f"`{item['change_date']}`",
                "",
                f"**Determination date:** "
                f"`{item['determination_date']}`",
                "",
                "**Answer / Reason:**",
                "",
                item["answer"],
                "",
            ]
        )

        if item["citations"]:

            lines.extend(
                [
                    "**Citations:** "
                    + ", ".join(
                        item["citations"]
                    ),
                    "",
                ]
            )

    RESULTS_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    RESULTS_PATH.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )


def main():

    print("=" * 70)
    print(
        "GROUNDED ANSWER — "
        "10-QUESTION EVALUATION"
    )
    print("=" * 70)

    print(
        "\nLoading existing production engine..."
    )

    components = build_pipeline()

    results = []

    print(
        "\nRunning 10 evaluation questions...\n"
    )

    for case in TEST_CASES:

        print(
            f"[{case['id']:02d}/10] "
            f"{case['name']}..."
        )

        # =============================================
        # IMPORTANT:
        # This is the ONLY engine call.
        # =============================================

        engine_result = process_question(
            question=case["question"],
            components=components,
        )

        passed = check_result(
            case,
            engine_result,
        )

        results.append(
            {
                "id": case["id"],
                "name": case["name"],
                "question": case["question"],
                "expected": case["expected_status"],
                "actual": engine_result["status"],
                "passed": passed,
                "topic": engine_result["topic"],
                "change_date": engine_result[
                    "change_date"
                ],
                "determination_date": engine_result[
                    "determination_date"
                ],
                "answer": engine_result[
                    "answer"
                ],
                "citations": engine_result[
                    "citations"
                ],
            }
        )

        print(
            "       "
            + (
                "PASS"
                if passed
                else "FAIL"
            )
            + f" ({engine_result['status']})"
        )

    write_results(
        results
    )

    total = len(results)

    passed = sum(
        1
        for result in results
        if result["passed"]
    )

    failed = total - passed

    print("\n" + "=" * 70)
    print("EVALUATION COMPLETE")
    print("=" * 70)

    print(
        f"\nTotal:  {total}"
    )

    print(
        f"Passed: {passed}"
    )

    print(
        f"Failed: {failed}"
    )

    print(
        f"\nResults saved to: "
        f"{RESULTS_PATH}"
    )

    if failed == 0:

        print(
            "\nALL 10 EVALUATION CASES PASSED."
        )

    else:

        print(
            "\nSOME EVALUATION CASES FAILED."
        )


if __name__ == "__main__":
    main()